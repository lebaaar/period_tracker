class RestoreDataPreviewPage extends StatefulWidget {
  final List sharedFiles;
  const RestoreDataPreviewPage({super.key, required this.sharedFiles});

  @override
  State<RestoreDataPreviewPage> createState() => _RestoreDataPreviewPageState();
}

class _RestoreDataPreviewPageState extends State<RestoreDataPreviewPage> {
  bool _onBoardingComplete = false;
  Map<String, dynamic>? _sharedFileContent;
  bool _loading = true;
  String? _error;
  bool _restoreError = false;
  bool _showErrorDetails = false;
  bool _alertShown = false;

  String? _name;
  List _periods = [];

  Future<void> _initialize() async {
    final isComplete = await getOnboardingComplete();
    if (!mounted) return;
    setState(() {
      _onBoardingComplete = isComplete;
      _loading = true;
      _error = null;
    });
    await clearFileShared();

    // try parsing the file
    try {
      // check if the file path is valid
      final String? filePath = widget.sharedFiles[0].path;
      if (filePath == null || filePath.isEmpty) {
        setState(() {
          _sharedFileContent = null;
          _loading = false;
          _error = '$kBackupFileName file not found';
        });
        return;
      }

      // check if the file exists
      final File file = File(filePath);
      if (!await file.exists()) {
        setState(() {
          _sharedFileContent = null;
          _loading = false;
          _error = '$kBackupFileName file not found';
        });
        return;
      }

      // read the file content
      final String? fileContent = await FileHelper.readFileContent(filePath);
      if (fileContent == null || fileContent.isEmpty) {
        setState(() {
          _sharedFileContent = null;
          _loading = false;
          _error = 'Backup file is empty';
        });
        return;
      }
      _sharedFileContent = ApplicationDataService().parseBackupFile(fileContent);
      if (_sharedFileContent == null) {
        setState(() {
          _loading = false;
          _error = 'Failed to parse backup file';
        });
        return;
      }

      // verify json file was generated by this app
      final String? appId = _sharedFileContent!['app'] as String?;
      if (appId == null || appId != kPackageName) {
        if (mounted) context.go(_onBoardingComplete ? '/' : '/onboarding');
        return;
      }

      // verify backup data structure and content
      final bool validBackupData = ApplicationDataService().isBackupDataValid(_sharedFileContent!);
      if (!validBackupData) {
        setState(() {
          _loading = false;
          _showErrorDetails = true;
          _error = 'Invalid backup file format. Please update the app on both your old and new devices to the latest version and try again.';
        });
        return;
      }

      // verify version compatibility
      final bool compatible = ApplicationDataService().verifyVersionCompatibility(_sharedFileContent!['databaseVersion'], kDatabaseVersion);
      if (!compatible) {
        setState(() {
          _loading = false;
          _showErrorDetails = true;
          _error = 'Incompatible backup file version. Please update the app on both your old and new devices to the latest version and try again.';
        });
        return;
      }

      setState(() {
        _sharedFileContent = _sharedFileContent!;
        _loading = false;
        _name = (_sharedFileContent!['database']['user'] as Map<String, dynamic>?)?['name'] as String?;
        _periods = (_sharedFileContent!['database']['periods']).map((e) => Period.fromMap(e as Map<String, dynamic>)).toList();
      });

      // show alert if onboarding is complete and we have a valid shared file
      WidgetsBinding.instance.addPostFrameCallback((_) => _maybeShowOnboardingAlert());
    } catch (e) {
      setState(() {
        _sharedFileContent = null;
        _loading = false;
        _error = e.toString();
      });
    }
  }

  Future<void> _maybeShowOnboardingAlert() async {
    if (!mounted || _alertShown || !_onBoardingComplete) return;
    _alertShown = true;
    final bool proceed = await showConfirm(
      context: context,
      title: 'Replace your current data?',
      message: 'This device already has an account. Restoring from this backup will replace your current data.',
      confirmLabel: 'Continue',
      cancelLabel: 'Exit restore',
    );
    if (!proceed && mounted) context.go('/');
  }

  @override
  void initState() {
    super.initState();
    _initialize();
  }

  void _restoreData() async {
    if (_sharedFileContent == null) return; // should not happen
    setState(() => _loading = true);

    final PeriodProvider periodProvider = context.read<PeriodProvider>();
    final SettingsProvider settingsProvider = context.read<SettingsProvider>();
    final UserProvider userProvider = context.read<UserProvider>();

    try {
      final success = await ApplicationDataService().restoreFromBackup(_sharedFileContent!);

      // wait a moment to show the spinner
      await Future.delayed(const Duration(milliseconds: 2000));

      if (success) {
        await setDisplayRestoreSuccess(true);

        // load data into providers
        await periodProvider.fetchPeriods();
        await settingsProvider.loadSettings();
        await userProvider.fetchUser();

        final User? user = userProvider.user;
        final Settings? settings = settingsProvider.settings;
        final DateTime? nextPeriodStartDate = periodProvider.getNextPeriodDate(settings?.predictionMode == 'dynamic', user?.cycleLength);

        if (nextPeriodStartDate != null && settings != null) {
          await NotificationService().scheduleNotificationsForNextPeriod(nextPeriodStartDate, settings.notificationDaysBefore, settings.notificationTime);
        }

        if (mounted) setState(() => _loading = false);

        // restart app to go to home page
        Restart.restartApp();
        return;
      }
    } catch (e) {
      if (!mounted) return;
      setState(() {
        _loading = false;
        _restoreError = true;
        _error = e.toString();
      });
    }
  }

  void openFeedback() {
    context.push(
      '/feedback',
      extra: FeedbackArgs(type: FeedbackType.bugReport, errorCode: kRestoreErrorCode, error: _error, sharedFileContent: _sharedFileContent),
    );
  }

  @override
  Widget build(BuildContext context) {
    final c = context.colors;
    final int periodCount = _periods.length;
    final String periodsText = periodCount == 0
        ? ''
        : periodCount == 1
        ? ', including 1 logged period,'
        : ', including $periodCount logged periods,';
    final String summary = _onBoardingComplete
        ? 'All your data$periodsText will be restored, replacing your existing data. Only continue if you want to replace it with the contents of the $kBackupFileName file.'
        : 'All your data$periodsText is ready to be restored.';
    final String errorText = _restoreError
        ? 'Something went wrong while restoring. Restart the app and try again. If that doesn\'t help, export the file on your old phone again.'
        : 'There is an issue with your $kBackupFileName file. Restart the app and try again. If that doesn\'t help, export the file on your old phone again.';
    final String exitRoute = _onBoardingComplete ? '/' : '/onboarding';

    Widget body;
    if (_loading) {
      body = Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          const CircularProgressIndicator(),
          const SizedBox(height: 20),
          Text('Restoring your data…', style: context.text.bodyMedium?.copyWith(color: c.labelSecondary)),
        ],
      );
    } else if (_error != null) {
      body = Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Container(
            width: 72,
            height: 72,
            decoration: BoxDecoration(color: c.late.withValues(alpha: 0.12), shape: BoxShape.circle),
            child: Icon(Icons.error_outline_rounded, size: 34, color: c.late),
          ),
          const SizedBox(height: 16),
          Text('Couldn\'t restore', style: context.text.headlineSmall),
          const SizedBox(height: 8),
          Text(
            errorText,
            textAlign: TextAlign.center,
            style: context.text.bodyMedium?.copyWith(color: c.labelSecondary),
          ),
          const SizedBox(height: 24),
          PrimaryButton(label: 'Exit restore', onPressed: () => context.go(exitRoute)),
          const SizedBox(height: 4),
          Pressable(
            onTap: openFeedback,
            child: Padding(
              padding: const EdgeInsets.all(12),
              child: Text('Report this issue', style: context.text.titleSmall?.copyWith(color: c.labelSecondary)),
            ),
          ),
          Pressable(
            onTap: () => setState(() => _showErrorDetails = !_showErrorDetails),
            child: Padding(
              padding: const EdgeInsets.all(8),
              child: Row(
                mainAxisSize: MainAxisSize.min,
                children: [
                  Text(_showErrorDetails ? 'Hide details' : 'Show details', style: context.text.bodySmall),
                  Icon(_showErrorDetails ? Icons.expand_less_rounded : Icons.expand_more_rounded, size: 18, color: c.labelSecondary),
                ],
              ),
            ),
          ),
          AnimatedSize(
            duration: const Duration(milliseconds: 200),
            curve: Curves.easeOutCubic,
            child: _showErrorDetails
                ? Padding(
                    padding: const EdgeInsets.all(8),
                    child: Text(_error ?? 'Unknown error', textAlign: TextAlign.center, style: context.text.bodySmall),
                  )
                : const SizedBox(width: double.infinity),
          ),
        ],
      );
    } else {
      final String greeting = _onBoardingComplete ? 'Welcome' : 'Welcome back';
      body = Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Container(
            width: 72,
            height: 72,
            decoration: BoxDecoration(color: c.accentSoft, shape: BoxShape.circle),
            child: Icon(Icons.restore_rounded, size: 34, color: c.label),
          ),
          const SizedBox(height: 16),
          Text(_name == null || _name!.isEmpty ? '$greeting!' : '$greeting, $_name!', textAlign: TextAlign.center, style: context.text.headlineSmall),
          const SizedBox(height: 8),
          Text(
            summary,
            textAlign: TextAlign.center,
            style: context.text.bodyMedium?.copyWith(color: c.labelSecondary),
          ),
          const SizedBox(height: 24),
          PrimaryButton(label: 'Restore my data', onPressed: _restoreData),
          const SizedBox(height: 4),
          Pressable(
            onTap: () => context.go(exitRoute),
            child: Padding(
              padding: const EdgeInsets.all(12),
              child: Text(
                _onBoardingComplete ? 'Keep my existing data' : 'Start fresh instead',
                style: context.text.titleSmall?.copyWith(color: c.labelSecondary),
              ),
            ),
          ),
        ],
      );
    }

    return Scaffold(
      backgroundColor: c.background,
      body: SafeArea(
        child: Center(
          child: SingleChildScrollView(padding: const EdgeInsets.symmetric(horizontal: 24, vertical: 24), child: body),
        ),
      ),
    );
  }
}
